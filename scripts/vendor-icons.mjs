// Regenerates the Vidstack icons in src/icons from media-icons raw/ (devDependency, pinned).
// Zest icons and the warning mark are hand-kept files and are not touched here.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const version = JSON.parse(readFileSync('node_modules/media-icons/package.json', 'utf8')).version;
const names = ['arrow-left', 'add', 'chevron-down', 'chevron-up', 'x-mark', 'fullscreen-arrow', 'fullscreen-arrow-exit',
    'play', 'pause', 'stop', 'search', 'menu-horizontal', 'arrow-up', 'arrow-down'];
const camel = (n) => n.replace(/-(\w)/g, (_, c) => c.toUpperCase());

for (const name of names) {
    const svg = readFileSync(join('node_modules/media-icons/raw', `${name}.svg`), 'utf8');
    const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
    const paths = [...svg.matchAll(/<path\s([^>]*?)\/>/g)].map((m) => {
        const attr = (a) => m[1].match(new RegExp(`(?:^|\\s)${a}="([^"]+)"`))?.[1];
        const d = attr('d');
        return attr('fill-rule') === 'evenodd' ? `{ d: '${d}', fillRule: 'evenodd' }` : `{ d: '${d}' }`;
    });
    writeFileSync(`src/icons/${camel(name)}.ts`, `// Origin: Vidstack media-icons@${version} (MIT), raw/${name}.svg. See THIRD_PARTY_NOTICES. Generated by scripts/vendor-icons.mjs; do not edit.
import type { IconData } from './types';

export const ${camel(name)}Icon: IconData = {
    viewBox: '${viewBox}',
    paths: [${paths.join(', ')}],
};
`);
}
